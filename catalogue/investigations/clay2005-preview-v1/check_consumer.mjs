import fs from 'node:fs';
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
const study=process.argv[2];
const {laboratoryExample}=await import(pathToFileURL(study+'/frozen/web/state-contract.mjs'));
const {normalizeSettings,settingsCsv}=await import(pathToFileURL(study+'/frozen/web/numerics.mjs'));
const model=JSON.parse(fs.readFileSync(study+'/models/hypoplastic-clay-2005.json'));
const html=fs.readFileSync(study+'/frozen/web/index.html','utf8');
const app=fs.readFileSync(study+'/frozen/web/app.js','utf8');
assert.match(html,/<input id="target"[^>]*value="1"/);
assert.match(html,/<input id="steps"[^>]*value="100"/);
assert.match(html,/<select id="protocol">\s*<option value="1">/);
assert.match(html,/<select id="cycles">\s*<option value="0">/);
assert.ok(app.includes("Number($('target').value)*(protocol===3?1000:.01)"));
const req=JSON.parse(fs.readFileSync(study+'/requests.json')).find(r=>r.id==='actual-browser-default');
const example=laboratoryExample(model),settings=normalizeSettings();
assert.deepEqual(example.initial,req.initial.split(',').map(Number));
assert.deepEqual(example.parameters,req.parameters.split(',').map(Number));
assert.deepEqual(settingsCsv(settings).split(',').map(Number),req.integration_settings.split(',').map(Number));
assert.deepEqual([req.protocol,req.target,req.steps,req.cycles],[1,.01,100,0]);
console.log(JSON.stringify({outcome:'passed',model_id:model.id,example,settings,request:req,compiled_execution:false},null,2));
