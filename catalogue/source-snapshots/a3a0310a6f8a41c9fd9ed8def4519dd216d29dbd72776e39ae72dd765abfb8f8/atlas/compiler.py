"""Deterministic, model-agnostic C++ code generation and catalogue export."""
import hashlib
import json
from pathlib import Path
from .dsl import Type, cpp, infer, parse
from .stress import stress_scope
from .model import ROOT, all_models, field_type, load, physical_time, integration_kind, equation_input_types, state_role



def reset_derived_types(model):
    symbols={'I':Type('sym'), **equation_input_types(model)}
    symbols.update({name:field_type(f) for name,f in model['parameters'].items()})
    for f in model['state']:
        symbols[f['name']]=symbols[f['name']+'_n']=field_type(f)
    result={}
    for f in model['derived']:
        symbols[f['name']]=result[f['name']]=infer(parse(f['expr']),symbols)
    return result


def finite_derived(name,typ):
    return f'if (!atlas_eval_ok || !atlas::finite_value({name})) return false;'


def generate(destination, model_paths=None):
    models=all_models() if model_paths is None else [load(p) for p in sorted(model_paths)]; dest=Path(destination); dest.mkdir(parents=True,exist_ok=True)
    has_solutions=any(m.get('solution_constraints') for m in models)
    required=max((sum(6 if f.get('shape')=='sym' else 1 for f in m['state']) for m in models),default=0)
    lines=['// Generated by atlas.compiler; edit model definitions, not this file.', '#pragma once',
           '#include "atlas/expm.hpp"', '#include "atlas/checked_trace.hpp"', '#include "atlas/checked_expression.hpp"', '#include <string>', '#include <vector>', '#include <limits>', 'namespace atlas {',
           f'static_assert(max_state >= {required} && max_derivatives >= {required + 6}, "Generated catalogue exceeds engine state/control derivative capacity");',
           'struct Field { std::string name; int offset; int size; double initial[6]; bool transient; bool multiplier; };',
           'struct Parameter { std::string name; double value, lower, upper; };',
           'struct Observable { std::string name; int offset, size; };',
           'enum class StressScope { unspecified, none, effective, total };',
           'struct Model { std::string id, name; bool rate; bool physical_time; std::vector<Field> fields; std::vector<Parameter> parameters; std::vector<Observable> observables; int stress_offset; bool axisymmetric; StressScope stress_scope=StressScope::unspecified; };',
           'inline const std::vector<Model>& models() { static const std::vector<Model> data = {']
    canonical=[]
    for i,m in enumerate(models):
        offset=0; fields=[]
        for f in m['state']:
            size=6 if f.get('shape')=='sym' else 1
            vals=f['initial'] if size==6 else [f['initial']]
            fields.append('{'+json.dumps(f['name'])+f', {offset}, {size}, '+'{'+','.join(repr(float(v)) for v in vals)+'}, '+str(state_role(f) != 'persistent').lower()+', '+str(state_role(f) == 'plastic_multiplier').lower()+'}')
            offset+=size
        params=['{'+json.dumps(n)+f", {float(p['default'])!r}, {float(p['min'])!r}, {float(p['max'])!r}"+'}' for n,p in m['parameters'].items()]
        observables=[];obs_offset=0;stress_offset=-1
        for obs in m.get('observables',[]):
            size=6 if obs['shape']=='sym' else 1
            observables.append('{'+json.dumps(obs['name'])+f',{obs_offset},{size}'+'}')
            if obs['name']=='stress':stress_offset=obs_offset
            obs_offset+=size
        lines.append('{'+json.dumps(m['id'])+','+json.dumps(m['name'])+','+str(integration_kind(m)=='rate').lower()+','+str(physical_time(m)).lower()+',{'+','.join(fields)+'},{'+','.join(params)+'},{'+','.join(observables)+'},'+str(stress_offset)+','+str(m.get('formulation',{}).get('kinematics')=='axisymmetric_x').lower()+',StressScope::'+stress_scope(m)+'},')
        if has_solutions:lines[-1]=lines[-1][:-2]+f',&solution_constraints_{i}'+lines[-1][-2:]
        canonical.append(m)
    lines+=['}; return data; }', 'template<class T> bool evaluate_model(int model, const std::vector<T>& z, const std::vector<T>& zn, const Sym<T>& loading, const std::vector<double>& params, std::vector<T>& out, bool check_initial=false, double evaluation_time=std::numeric_limits<double>::quiet_NaN(), bool check_only=false, bool observables_only=false) {', 'bool atlas_eval_ok=true;', 'const auto I = identity<T>();', '(void)evaluation_time;', 'switch(model) {']
    obs_scales=['inline std::vector<double> model_observable_scales(int model,const std::vector<double>& params) { using T=double; bool atlas_eval_ok=true; switch(model) {']
    scales=['inline std::vector<double> model_scales(int model,const std::vector<double>& params) { using T=double; bool atlas_eval_ok=true; switch(model) {']
    for i,m in enumerate(models):
        reset_types=reset_derived_types(m)
        lines.append(f'case {i}: {{'); scales.append(f'case {i}: {{'); obs_scales.append(f'case {i}: {{')
        if m.get('schema_version') == '0.3':
            # Declared inputs are required even when absent from the AST. Check
            # primal loading here; executed-node checks retain Jet derivative rules.
            lines.append('for (const auto& component : loading.v) if (!std::isfinite(atlas::value(component))) return false;')
        if physical_time(m):
            lines += ['if (!std::isfinite(evaluation_time)) return false;', 'const T time=T(evaluation_time);', 'const auto& strain_rate=loading;']
        else:
            lines.append('const auto& de=loading;')
        if m.get('formulation',{}).get('kinematics')=='axisymmetric_x':
            lines.append('if (!axisymmetric_x(loading)) return false;')
        for j,name in enumerate(m['parameters']):
            decl=f'const T {name} = T(params.at({j}));'
            lines.append(decl); scales.append(decl); obs_scales.append(decl)
        offset=0; scal=[]
        for f in m['state']:
            n=f['name']; size=6 if f.get('shape')=='sym' else 1
            if size==6:
                lines+= [f'const auto {n} = tensor_from(z,{offset});',f'const auto {n}_n = tensor_from(zn,{offset});']
            else: lines += [f'const T {n}=z.at({offset});',f'const T {n}_n=zn.at({offset});']
            scal.extend([cpp(parse(f['scale']))]*size);offset+=size
        for f in m['derived']:
            lines.append(f"const auto {f['name']} = {cpp(parse(f['expr']))};")
            lines.append(finite_derived(f['name'],reset_types[f['name']]))
        lines.append('if (!('+' && '.join(cpp(parse(c)) for c in m['domain'])+')) return false;' if m['domain'] else '')
        if m.get('initial_checks'):
            lines.append('if (check_initial && !('+' && '.join(cpp(parse(c)) for c in m['initial_checks'])+')) return false;')
        lines.append('if (!atlas_eval_ok) return false;')
        lines.append('if (check_only) return true;')
        observables=m.get('observables',[])
        obs_count=sum(6 if f['shape']=='sym' else 1 for f in observables)
        lines += ['if (observables_only) {',f'out.resize({obs_count});']
        obs_scale=[];obs_offset=0
        for f in observables:
            expr=cpp(parse(f['expr']));size=6 if f['shape']=='sym' else 1
            lines.append(f'put_tensor(out,{obs_offset},{expr});' if size==6 else f'out[{obs_offset}]={expr};')
            obs_scale.extend([cpp(parse(f['scale']))]*size);obs_offset+=size
        stress_offset=next((sum(6 if f['shape']=='sym' else 1 for f in observables[:i]) for i,f in enumerate(observables) if f['name']=='stress'),-1)
        if m.get('formulation',{}).get('kinematics')=='axisymmetric_x' and stress_offset>=0:
            lines.append(f'if (!axisymmetric_x(tensor_from(out,{stress_offset}))) return false;')
        lines += ['return atlas_eval_ok && std::all_of(out.begin(),out.end(),[](const auto& v){return atlas::finite_value(v);});','}']
        obs_scales += ['auto result=std::vector<double>{'+','.join(obs_scale)+'};', 'if (!atlas_eval_ok) for(auto& value:result) value=std::numeric_limits<double>::quiet_NaN();', 'return result;','}']
        lines.append(f'out.resize({offset});')
        offset=0
        for f in m['state']:
            ex=cpp(parse(m['equations'][f['name']]))
            if f.get('shape')=='sym':
                lines.append(f'put_tensor(out,{offset},{ex});'); offset+=6
            else: lines.append(f'out[{offset}]={ex};');offset+=1
        lines+=['return atlas_eval_ok && std::all_of(out.begin(),out.end(),[](const auto& v){return atlas::finite_value(v);});', '}']
        scales+=['auto result=std::vector<double>{'+','.join(scal)+'};', 'if (!atlas_eval_ok) for(auto& value:result) value=std::numeric_limits<double>::quiet_NaN();', 'return result;','}']
    lines+=['default: return false;','}','}']; scales+=['default: return {};','}','}']; obs_scales+=['default: return {};','}','}']
    resets=['template<class T> bool prepare_model_increment(int model,const std::vector<T>& zn,const Sym<T>& loading,const std::vector<double>& params,std::vector<T>& out,bool* reset_boundary=nullptr) {',
            'if(reset_boundary) *reset_boundary=false;',
            'bool atlas_eval_ok=true; (void)params; const auto I=identity<T>(); const auto& de=loading; out=zn; switch(model) {']
    for i,m in enumerate(models):
        updates=m.get('increment_reset',{}).get('updates',[])
        if not updates:continue
        reset_types=reset_derived_types(m)
        resets.append(f'case {i}: {{')
        for j,name in enumerate(m['parameters']):resets.append(f'const T {name}=params.at({j});')
        offset=0;offsets={}
        for f in m['state']:
            n=f['name'];size=6 if f['shape']=='sym' else 1;offsets[n]=offset
            resets.append(f'const auto {n}=tensor_from(zn,{offset});' if size==6 else f'const T {n}=zn.at({offset});')
            resets.append(f'const auto {n}_n={n};');offset+=size
        for f in m['derived']:
            resets.append(f"const auto {f['name']}={cpp(parse(f['expr']))};")
            resets.append(finite_derived(f['name'],reset_types[f['name']]))
        for update in updates:
            guard=cpp(parse(update['guard']));value=cpp(parse(update['value']));target=update['target']
            resets.append(f'if (!atlas::finite_value({guard}) || !atlas_eval_ok) return false;')
            resets.append(f'if (reset_boundary && atlas::value({guard}) == 0.) *reset_boundary=true;')
            size=next(f['shape'] for f in m['state'] if f['name']==target)
            assignment=f'put_tensor(out,{offsets[target]},{value});' if size=='sym' else f'out[{offsets[target]}]={value};'
            resets.append(f'if (atlas::value({guard}) < 0.) {{ {assignment} }}')
        resets+=['break;','}']
    resets+=['default: break;', '}', 'return atlas_eval_ok && std::all_of(out.begin(),out.end(),[](const auto& x){return atlas::finite_value(x);});','}']
    lines+=resets
    digest=hashlib.sha256(json.dumps(canonical,sort_keys=True,separators=(',',':')).encode()).hexdigest()
    catalogue={'schema_version':'0.1','sha256':digest,'models':canonical}
    explicit_cases=''.join(f'case {i}: return true;' for i,m in enumerate(models) if m['schema_version']=='0.3')
    lines+=scales+obs_scales+[
                   'inline bool explicit_initialization_required(int model) { switch(model) {'+explicit_cases+'default: return false;} }',
                   f'inline const char* catalogue_hash() {{ return "{digest}"; }}',
                   'inline const char* describe_models() { return '+json.dumps(json.dumps(catalogue,separators=(',',':')))+'; }','}']
    if has_solutions:
        declarations=[]
        for i,m in enumerate(models):
            count=sum(6 if f['shape']=='sym' else 1 for f in m['state'])
            declarations += [f'inline bool solution_constraints_{i}(const std::vector<double>& z,const std::vector<double>& params) {{',
                f'if(z.size()!={count} || params.size()!={len(m["parameters"])}) return false;',
                'for(double x:z) if(!std::isfinite(x)) return false;',
                'using T=double; bool atlas_eval_ok=true; const auto I=identity<T>();']
            for j,(name,f) in enumerate(m['parameters'].items()):
                declarations += [f'const T {name}=params[{j}];',f'if(!std::isfinite({name}) || {name} < {float(f["min"])!r} || {name} > {float(f["max"])!r}) return false;']
            offset=0
            for f in m['state']:
                if state_role(f)=='persistent':
                    declarations.append(f'const auto {f["name"]}=tensor_from(z,{offset});' if f['shape']=='sym' else f'const T {f["name"]}=z[{offset}];')
                offset+=6 if f['shape']=='sym' else 1
            condition=' && '.join(cpp(parse(c)) for c in m.get('solution_constraints',[])) or 'true'
            declarations += [f'const bool result=({condition});','return result && atlas_eval_ok;','}']
        index=next(i for i,l in enumerate(lines) if l.startswith('inline const std::vector<Model>& models()'))
        lines[index:index]=declarations
        index=next(i for i,l in enumerate(lines) if l.startswith('struct Model {'))
        lines[index]=lines[index].replace('StressScope stress_scope=StressScope::unspecified;','StressScope stress_scope=StressScope::unspecified; bool (*solution_check)(const std::vector<double>&,const std::vector<double>&)=nullptr;')
        index=next(i for i,l in enumerate(lines) if l.startswith('template<class T> bool evaluate_model('))
        helper=['template<class T> bool generated_solution_constraints(int model,const std::vector<T>& state,const std::vector<double>& params) {',
                'if(model<0 || model>=int(models().size())) return false;',
                'std::vector<double> primal; for(const auto& x:state) { if(!finite_value(x)) return false; primal.push_back(value(x)); }',
                'return models()[model].solution_check(primal,params);','}']
        lines[index:index]=helper
        index=next(i for i,l in enumerate(lines) if l.startswith('template<class T> bool evaluate_model('))
        lines.insert(index+1,'if((check_initial || observables_only) && !generated_solution_constraints(model,z,params)) return false;')
    # Existing catalogues retain byte-identical headers until they use the new
    # operation. Detect emitted calls across every generated context.
    if any('atlas::determinant_or_mark(' in line for line in lines):
        lines.insert(2, '#include "atlas/checked_determinant.hpp"')
    if any('atlas::principal_centered_mid_gt_or_mark(' in line for line in lines):
        lines.insert(2, '#include "atlas/checked_centered_middle.hpp"')
    if any('atlas::principal_max_repeated_or_mark(' in line or 'atlas::principal_min_repeated_or_mark(' in line for line in lines):
        lines.insert(2, '#include "atlas/checked_spectral_multiplicity.hpp"')
    if any('atlas::principal_range_le_or_mark(' in line for line in lines):
        lines.insert(2, '#include "atlas/checked_principal_range.hpp"')
    if any('atlas::normalized_determinant_or_mark(' in line for line in lines):
        lines.insert(2, '#include "atlas/checked_normalized_determinant.hpp"')
    if any('atlas::spectral_scalar_or_mark(' in line or 'atlas::spectral_projector_or_mark(' in line for line in lines):
        lines.insert(2, '#include "atlas/checked_spectral.hpp"')
    (dest/'models.hpp').write_text('\n'.join(lines)+'\n')
    (dest/'models.json').write_text(json.dumps({'schema_version':'0.1','sha256':digest,'models':canonical},indent=2)+'\n')
    return models


if __name__=='__main__':
    import sys
    generate(sys.argv[1] if len(sys.argv)>1 else ROOT/'build/generated',
             list(Path(sys.argv[2]).glob('*.json')) if len(sys.argv)>2 else None)
