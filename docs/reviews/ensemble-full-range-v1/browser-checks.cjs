async (page) => {
  const assert = (condition, message) => { if (!condition) throw Error(message); };
  const completed = async (count) => page.waitForFunction(n => document.querySelector('#ensemble-status')?.textContent === n+' completed', count);
  const checks = [];
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:18869/#ensemble');
  await page.reload();
  await page.waitForSelector('#ensemble[data-ready="true"]');
  await page.locator('#ensemble-run').click();
  await completed(15);
  assert(await page.locator('#ensemble-runs [data-status="completed"]').count() === 15, 'All default outcomes retained');
  checks.push('15 default real Wasm completions');
  await page.locator('#ensemble-runs button').last().click();
  assert((await page.locator('#ensemble-selected').textContent()).includes('kappa'), 'Selected exact inputs');
  const lines = await page.locator('#ensemble-stress polyline').count();
  await page.getByRole('checkbox',{name:'Drucker–Prager',exact:true}).uncheck();
  assert(await page.locator('#ensemble-stress polyline').count() === lines-5, 'Model visibility');
  await page.getByRole('checkbox',{name:'Drucker–Prager',exact:true}).check();
  for(const chart of ['stress','volume']) {
    const lengths=await page.locator('#ensemble-'+chart+' polyline').evaluateAll(lines=>lines.map(el=>el.getAttribute('points').split(' ').length));
    assert(lengths.length===16 && lengths.every(n=>n===1438),'Full source and every model endpoint plotted');
  }
  const recorded=JSON.parse(await page.locator('#ensemble-selected').textContent());
  assert(recorded.specification.path.knots.at(-1).targets[0]===.1599,'Final requested strain');
  checks.push('Selection, model visibility, all1438 measured/model endpoints, final15.99% strain');
  const downloaded = page.waitForEvent('download');
  await page.locator('#ensemble-export').click();
  await (await downloaded).saveAs('output/playwright/ensemble-full-range-export.json');
  await page.locator('[data-variation="E"]').fill('25000000');
  assert((await page.locator('#ensemble-status').textContent()).includes('stale'), 'Edits mark stale');
  assert(await page.locator('#ensemble-export').isDisabled(), 'Stale export disabled');
  await page.locator('#ensemble-file').setInputFiles('output/playwright/ensemble-full-range-export.json');
  await completed(15);
  assert(await page.locator('[data-variation="E"]').inputValue() === '24000000, 36000000', 'Import restores configuration before fresh replay');
  checks.push('Export, edit-stale and import with fresh replay');
  await page.locator('[data-parameter="E"]').first().fill('');
  await page.getByRole('checkbox',{name:'Include this model',exact:true}).first().uncheck();
  assert(await page.locator('[data-parameter="E"]').first().isDisabled(), 'Excluded invalid model fields disabled');
  await page.locator('#ensemble-run').click();
  await completed(10);
  checks.push('Excluded model ignores incomplete inputs');
  await page.locator('#ensemble-file').setInputFiles('output/playwright/ensemble-full-range-export.json');
  await completed(15);
  await page.locator('summary').filter({hasText:'Drucker–Prager'}).click();
  await page.locator('[data-variation="Md"]').fill('-1');
  await page.locator('#ensemble-run').click();
  await page.waitForFunction(() => document.querySelector('#ensemble-status').textContent === '13 completed · 1 rejected');
  await page.locator('#ensemble-runs [data-status="rejected"]').click();
  assert(await page.locator('#ensemble-single-export').isDisabled(), 'Rejected run cannot export a response');
  checks.push('Rejected variation retained alongside completed runs');
  await page.route('**/ensemble-worker.mjs', async route => {await new Promise(r=>setTimeout(r,350));try{await route.continue();}catch{}});
  await page.locator('#ensemble-run').click();
  await page.locator('#ensemble-cancel').click();
  await page.waitForFunction(() => !document.querySelector('#ensemble-status').textContent.includes('Running'));
  assert((await page.locator('#ensemble-status').textContent()).includes('cancelled'), 'Cancellation retained');
  await page.unrouteAll({behavior:'ignoreErrors'});
  checks.push('Cancellation terminates delayed worker and pending queue');
  await page.getByRole('link',{name:'≋ Methods & evidence',exact:true}).click();
  await page.locator('#ensemble').waitFor({state:'hidden'});
  await page.getByRole('link',{name:'≋ Ensemble explorer',exact:true}).click();
  await page.locator('#ensemble').waitFor({state:'visible'});
  checks.push('Navigate away and return');
  await page.locator('#ensemble-file').setInputFiles('output/playwright/ensemble-full-range-export.json');
  await completed(15);
  await page.waitForFunction(() => getComputedStyle(document.querySelector('#toast')).display === 'none');
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:'output/playwright/ensemble-full-range-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  const geometry=await page.locator('.ensemble-layout').evaluate(el=>{
    const a=el.children[0].getBoundingClientRect(),b=el.children[1].getBoundingClientRect();
    return {width:document.documentElement.scrollWidth,controlsWidth:a.width,resultsBelow:b.top>=a.bottom-1};
  });
  assert(geometry.width === 390 && geometry.controlsWidth > 300 && geometry.resultsBelow, 'Mobile single column layout');
  await page.screenshot({path:'output/playwright/ensemble-full-range-mobile.png',fullPage:true});
  checks.push('Desktop and 390px mobile layout');
  console.log(JSON.stringify({status:'passed',checks,mobile:geometry}));
}
