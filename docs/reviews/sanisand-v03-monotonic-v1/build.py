"""Build one explicit normal atlas_solver target, with retained process receipts."""
import argparse
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import time
from assess import HERE, FREEZE, ROOT, load, sha, require
from run import verify_execution_freeze


def command(argv,destination,name):
    started=time.monotonic()
    result=subprocess.run(argv,capture_output=True,text=True)
    receipt={'argv':argv,'returncode':result.returncode,'stdout':result.stdout,'stderr':result.stderr,'elapsed_seconds':time.monotonic()-started}
    (destination/(name+'.json')).write_text(json.dumps(receipt,indent=2)+'\n')
    print(json.dumps({'command':name,'returncode':result.returncode,'elapsed_seconds':receipt['elapsed_seconds']}),flush=True)
    return result.returncode


def build(backend,stage):
    verify_execution_freeze()
    if backend=='native':
        spec=importlib.util.spec_from_file_location('sanisand_preparation',FREEZE/'prepare.py');m=importlib.util.module_from_spec(spec)
        sys.path.insert(0,str(FREEZE));spec.loader.exec_module(m);m.prepare(stage)
    else:
        native=load(stage/'native/build-receipt.json')
        require(native['returncode']==0,'native must build first')
        require((stage/'native-results/index.json').exists(),'native must execute first')
        require(load(stage/'native-assessment.json')['research_qualification_pass'] is True, 'native gates failed; retain failure and stop before Wasm')
        for name,expected in load(FREEZE/'source-pins.json')['files'].items():require(sha(stage/name)==expected,'staged source '+name)
    require(sha(stage/'models/research-sanisand-2004-fixed-memory-be-v03.json')==sha(FREEZE/'model.json'),'staged candidate')
    out=stage/backend;out.mkdir(exist_ok=False)
    configure=['/opt/homebrew/bin/cmake','-S',str(stage),'-B',str(out),'-DCMAKE_BUILD_TYPE=Release','-DPython3_EXECUTABLE='+sys.executable]
    if backend=='wasm':configure.insert(0,'/opt/homebrew/bin/emcmake')
    code=command(configure,out,'configure')
    if code==0:code=command(['/opt/homebrew/bin/cmake','--build',str(out),'--target','atlas_solver','--parallel','1'],out,'build')
    artifacts={};executable=out/('atlas_solver' if backend=='native' else 'atlas.js')
    if code==0:
        for path in [executable]+([out/'atlas.wasm'] if backend=='wasm' else []):artifacts[str(path)]=sha(path)
        expected=load(FREEZE/'preflight.json')['generated']
        for name,h in expected.items():require(sha(out/name)==h,'normal generated bytes '+name)
        if backend=='wasm':
            (out/'package.json').write_text('{"type":"module"}\n');artifacts[str(out/'package.json')]=sha(out/'package.json')
    receipt={'backend':backend,'returncode':code,'executable':str(executable),'artifacts':artifacts,'stage':str(stage),'generated':load(FREEZE/'preflight.json')['generated'],'execution_freeze_sha256':sha(HERE/'execution-freeze.json')}
    (out/'build-receipt.json').write_text(json.dumps(receipt,indent=2)+'\n')
    return code


if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('backend',choices=['native','wasm']);p.add_argument('stage',type=Path);a=p.parse_args()
    raise SystemExit(build(a.backend,a.stage.resolve()))
