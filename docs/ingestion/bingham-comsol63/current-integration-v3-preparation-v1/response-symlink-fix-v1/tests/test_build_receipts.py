def write(path,data):
 path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(data if isinstance(data,bytes) else data.encode())
def archive(objects):
 out=b'!<arch>\n'
 for obj in objects:
  body=obj.read_bytes();name=obj.name+'/'
  header=f'{name:<16}{0:<12}{0:<6}{0:<6}{100644:<8}{len(body):<10}`\n'.encode()
  assert len(header)==60
  out+=header+body+(b'\n' if len(body)%2 else b'')
 return out
