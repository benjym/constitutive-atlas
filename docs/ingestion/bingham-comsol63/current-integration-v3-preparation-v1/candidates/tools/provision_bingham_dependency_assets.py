"""Restore the fixed E5-bound Maxwell/NorSand assets; never build or run a law.

Both unchanged packaging guards must accept staged directories before installation.
No source-equivalence assertion or scientific review is generated by this helper.
"""
import argparse
import ctypes
from contextlib import ExitStack
import hashlib
import io
import json
import os
from pathlib import Path
import stat
import sys
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
MODEL = 'bingham-comsol63-mises-perfect-zero-spin-ode'
MODEL_SHA256 = '6c5ee29c5c8cfbe18eaac09808a86ed7b656c8716511409bb23ecd0d3ad89850'
PACKET = 'docs/ingestion/bingham-comsol63/current-engine-equivalence-v1/qualified-packaging-v1/'
INDEX = PACKET + 'INDEX.json'
ARCHIVE = PACKET + 'qualified-engines.zip'
INDEX_SHA256 = '5606f1ab6b50a3c85c5577c10afbecbc083ce6616cdf74aab91e061d1d67ed14'
ARCHIVE_SHA256 = '2554747b771125373fbdc90f75391ec5a06359b8bf9c6384e79f7e83a494a1f6'
# Fixed exact twelve-file layout and sizes, read from the retained qualified archive.
MEMBERS = {
    'maxwell/maxwell.js': 27124,
    'maxwell/maxwell.wasm': 399350,
    'maxwell/generated/models.json': 5014,
    'maxwell/maxwell-qualification.json': 3983,
    'maxwell/build-review.json': 3937,
    'norsand/atlas_path_capability.mjs': 15867,
    'norsand/atlas_path_capability.wasm': 51299,
    'norsand/generated/path_api.cpp': 3562,
    'norsand/generated/path_catalogue.json': 13438,
    'norsand/generated/path_models.hpp': 17991,
    'norsand/controlled-path-qualification.json': 15893,
    'norsand/build-review.json': 30422,
}
ARCHIVE_LIMIT = 16 * 1024 * 1024


def digest(data):
    return hashlib.sha256(data).hexdigest()


def _json(data):
    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError('Duplicate JSON key: ' + key)
            result[key] = value
        return result
    return json.loads(data, object_pairs_hook=unique)


def _repo_file(relative):
    name = Path(relative)
    path = ROOT / name
    if name.is_absolute() or '..' in name.parts or path.is_symlink() or not path.resolve().is_relative_to(ROOT.resolve()):
        raise ValueError('Unsafe dependency receipt path: ' + str(relative))
    if not stat.S_ISREG(path.stat().st_mode):
        raise ValueError('Dependency receipt is not a regular file: ' + str(relative))
    return path


def _reviewed_assets():
    # Imported lazily: pure archive/security tests never invoke scientific guards.
    sys.path.insert(0, str(ROOT))
    from atlas.agent_review import approval_entry, validate_review
    registry_bytes = _repo_file('catalogue/approved-models.json').read_bytes()
    registry = _json(registry_bytes)
    matches = [entry for entry in registry['models'] if entry['model_id'] == MODEL]
    if len(matches) != 1:
        raise ValueError('Canonical accepted Bingham E5 approval is required')
    approval = matches[0]
    review_name = approval['review']['path']
    if not review_name.startswith('catalogue/agent-reviews/') or not review_name.endswith('.json'):
        raise ValueError('Bingham review must use the canonical review registry')
    review_path = _repo_file(review_name)
    review = validate_review(review_path, root=ROOT, for_approval=True)
    if approval != approval_entry(review_path, root=ROOT) or review['model']['id'] != MODEL or review['model']['sha256'] != MODEL_SHA256:
        raise ValueError('Bingham canonical approval/model/review disagreement')
    pins = {entry['path']: entry['sha256'] for entry in review['artifacts']}
    index_bytes = _repo_file(INDEX).read_bytes()
    archive_bytes = _repo_file(ARCHIVE).read_bytes()
    if digest(index_bytes) != INDEX_SHA256 or pins.get(INDEX) != INDEX_SHA256 or digest(archive_bytes) != ARCHIVE_SHA256 or pins.get(ARCHIVE) != ARCHIVE_SHA256:
        raise ValueError('Fixed dependency index/archive must be bound to actual accepted Bingham E5 review')
    index = _json(index_bytes)
    if index.get('identity') != 'bingham-current-dependency-assets-v1' or index.get('archive') != ARCHIVE or index.get('archive_sha256') != ARCHIVE_SHA256 or set(index.get('files', {})) != set(MEMBERS):
        raise ValueError('Unexpected fixed dependency asset index')
    binding = dict(registry_sha256=digest(registry_bytes), review_sha256=digest(review_path.read_bytes()), index_sha256=digest(index_bytes), archive_sha256=digest(archive_bytes))
    return index, archive_bytes, binding


def _selected_files(index, archive_bytes):
    if len(archive_bytes) > ARCHIVE_LIMIT or digest(archive_bytes) != ARCHIVE_SHA256 or set(index.get('files', {})) != set(MEMBERS):
        raise ValueError('Changed or oversized exact dependency archive/index')
    result = {}
    with zipfile.ZipFile(io.BytesIO(archive_bytes)) as archive:
        entries = archive.infolist()
        names = [entry.filename for entry in entries]
        if len(names) != 12 or len(names) != len(set(names)) or set(names) != set(MEMBERS):
            raise ValueError('Dependency ZIP must contain exactly the twelve unique allowlisted members')
        for entry in entries:
            name = entry.filename
            mode = entry.external_attr >> 16
            if entry.orig_filename != name or entry.create_system != 3 or not stat.S_ISREG(mode) or mode & 0o7000 or entry.is_dir() or entry.flag_bits & 1 or entry.compress_type not in (zipfile.ZIP_STORED, zipfile.ZIP_DEFLATED) or entry.file_size != MEMBERS[name]:
                raise ValueError('Nonregular, unsafe or incorrectly sized dependency member: ' + name)
            with archive.open(entry) as stream:
                data = stream.read(MEMBERS[name] + 1)
            if len(data) != MEMBERS[name] or digest(data) != index['files'][name]:
                raise ValueError('Dependency member differs from exact reviewed bytes: ' + name)
            result[name] = data
    return result


def _destination(value):
    path = Path(value).absolute()
    if '..' in path.parts or path.exists() or path.is_symlink():
        raise ValueError('Refusing existing or unsafe dependency destination: ' + str(path))
    if any(parent.is_symlink() for parent in path.parents):
        raise ValueError('Dependency destination parent is a symlink: ' + str(path))
    return path


def _directory_fd(value):
    """Pin every parent component without following a concurrently introduced link."""
    path = Path(value).absolute()
    if '..' in path.parts:
        raise ValueError('Unsafe directory path')
    flags = os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW
    descriptor = os.open(path.anchor, flags)
    try:
        for part in path.parts[1:]:
            following = os.open(part, flags, dir_fd=descriptor)
            os.close(descriptor)
            descriptor = following
        return descriptor
    except BaseException:
        os.close(descriptor)
        raise


def _rename_no_replace(source, destination):
    """Atomic directory rename that fails even if a concurrent empty target appears."""
    library = ctypes.CDLL(None, use_errno=True)
    source_fd = _directory_fd(Path(source).parent)
    try:
        destination_fd = _directory_fd(Path(destination).parent)
        try:
            arguments = [source_fd, os.fsencode(Path(source).name), destination_fd, os.fsencode(Path(destination).name)]
            if sys.platform.startswith('linux'):
                function = getattr(library, 'renameat2', None)
                rename_flag = 1  # Linux RENAME_NOREPLACE.
            elif sys.platform == 'darwin':
                function = getattr(library, 'renameatx_np', None)
                rename_flag = 0x00000004  # Apple RENAME_EXCL.
            else:
                raise RuntimeError('Atomic no-replace directory installation requires supported Linux/macOS')
            if function is None:
                raise RuntimeError('Atomic no-replace directory rename is unavailable')
            function.argtypes = [ctypes.c_int, ctypes.c_char_p, ctypes.c_int, ctypes.c_char_p, ctypes.c_uint]
            function.restype = ctypes.c_int
            if function(*arguments, rename_flag):
                error = ctypes.get_errno()
                raise OSError(error, os.strerror(error), str(destination))
        finally:
            os.close(destination_fd)
    finally:
        os.close(source_fd)


def _guard(stages, verification):
    sys.path.insert(0, str(ROOT))
    from tools.build_maxwell_laboratory import bundle as maxwell_bundle
    from tools.build_controlled_path_web import bundle as norsand_bundle
    maxwell_bundle(verification['maxwell'], stages['maxwell'])
    norsand_bundle(verification['norsand'], stages['norsand'])


def _verify_staged(stages, files):
    for group, directory in stages.items():
        if directory.is_symlink() or not directory.is_dir():
            raise ValueError('Staged dependency root is not a regular directory: ' + group)
        expected = {name.split('/', 1)[1]: data for name, data in files.items() if name.startswith(group + '/')}
        actual = {path.relative_to(directory).as_posix() for path in directory.rglob('*') if path.is_file() or path.is_symlink()}
        if actual != set(expected):
            raise ValueError('Staged dependency file layout changed: ' + group)
        for relative, data in expected.items():
            path = directory / relative
            if path.is_symlink() or not stat.S_ISREG(path.stat().st_mode) or path.read_bytes() != data:
                raise ValueError('Staged dependency bytes changed: ' + group + '/' + relative)


def provision(maxwell_output, norsand_output):
    destinations = {'maxwell': _destination(maxwell_output), 'norsand': _destination(norsand_output)}
    paths = list(destinations.values())
    if paths[0] == paths[1] or paths[0].is_relative_to(paths[1]) or paths[1].is_relative_to(paths[0]):
        raise ValueError('Dependency destinations must be distinct and nonnested')
    index, archive_bytes, binding = _reviewed_assets()
    files = _selected_files(index, archive_bytes)
    installed = []
    with ExitStack() as cleanup:
        stages, verification = {}, {}
        for group, destination in destinations.items():
            destination.parent.mkdir(parents=True, exist_ok=True)
            _destination(destination)
            temporary = Path(cleanup.enter_context(tempfile.TemporaryDirectory(prefix='.bingham-dependency-', dir=destination.parent)))
            stages[group] = temporary / 'build'
            verification[group] = temporary / 'guard-output'
        for name, data in files.items():
            group, relative = name.split('/', 1)
            target = stages[group] / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        _guard(stages, verification)
        _verify_staged(stages, files)
        if _reviewed_assets() != (index, archive_bytes, binding):
            raise ValueError('Accepted review/index/archive changed while provisioning')
        for destination in destinations.values():
            _destination(destination)
        try:
            for group, destination in destinations.items():
                _rename_no_replace(stages[group], destination)
                installed.append(str(destination))
        except Exception as error:
            raise RuntimeError('Dependency installation stopped; already installed verified directories retained: ' + repr(installed)) from error
    return {'status': 'passed', 'binding': binding, 'destinations': {name: str(path) for name, path in destinations.items()}, 'files': {name: digest(data) for name, data in files.items()}, 'scope': 'Fixed independently reviewed dependency bytes and unchanged packaging guards; no new build or scientific calculation'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--maxwell-output', type=Path, default=ROOT / 'build-maxwell-wasm')
    parser.add_argument('--controlled-path-output', type=Path, default=ROOT / 'build-controlled-path-public')
    arguments = parser.parse_args()
    print(json.dumps(provision(arguments.maxwell_output, arguments.controlled_path_output), indent=2))
